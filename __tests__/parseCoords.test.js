import { parseCoords } from '../src/parseCoords';

describe('parseCoords', () => {
  // Валидные форматы

  test('формат с пробелом: "51.50851, -0.12572"', () => {
    const result = parseCoords('51.50851, -0.12572');
    expect(result).toEqual({ lat: 51.50851, lng: -0.12572 });
  });

  test('формат без пробела: "51.50851,-0.12572"', () => {
    const result = parseCoords('51.50851,-0.12572');
    expect(result).toEqual({ lat: 51.50851, lng: -0.12572 });
  });

  test('формат с квадратными скобками: "[51.50851, -0.12572]"', () => {
    const result = parseCoords('[51.50851, -0.12572]');
    expect(result).toEqual({ lat: 51.50851, lng: -0.12572 });
  });

  test('формат с квадратными скобками без пробела: "[51.50851,-0.12572]"', () => {
    const result = parseCoords('[51.50851,-0.12572]');
    expect(result).toEqual({ lat: 51.50851, lng: -0.12572 });
  });

  test('пробелы вокруг значений обрезаются', () => {
    const result = parseCoords('  51.50851 ,  -0.12572  ');
    expect(result).toEqual({ lat: 51.50851, lng: -0.12572 });
  });

  // Невалидные форматы — генерируют исключение

  test('пустая строка — генерирует исключение', () => {
    expect(() => parseCoords('')).toThrow('Некорректный формат координат');
  });

  test('только одно число — генерирует исключение', () => {
    expect(() => parseCoords('51.50851')).toThrow('Некорректный формат координат');
  });

  test('текст вместо чисел — генерирует исключение', () => {
    expect(() => parseCoords('привет, мир')).toThrow('Некорректный формат координат');
  });

  test('три числа — генерирует исключение', () => {
    expect(() => parseCoords('51.50851, -0.12572, 100')).toThrow('Некорректный формат координат');
  });

  test('не строка — генерирует исключение', () => {
    expect(() => parseCoords(null)).toThrow('Некорректный формат координат');
  });

  test('широта вне диапазона — генерирует исключение', () => {
    expect(() => parseCoords('91, 0')).toThrow('Некорректный формат координат');
  });

  test('долгота вне диапазона — генерирует исключение', () => {
    expect(() => parseCoords('0, 181')).toThrow('Некорректный формат координат');
  });
});
